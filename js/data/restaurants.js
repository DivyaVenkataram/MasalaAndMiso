/** For map: only entries with coordinates; michelin label for display */
function getRestaurantsForMap() {
  return RESTAURANTS.filter((r) => r.coordinates && r.coordinates.lat).map((r) => ({
    name: r.name,
    city: r.city,
    lat: r.coordinates.lat,
    lng: r.coordinates.lng,
    michelin: r.michelinDistinction
      ? (r.michelinYear ? `${r.michelinDistinction} ${r.michelinYear}` : r.michelinDistinction)
      : '—',
    score: r.overallScore,
    cuisine: r.cuisine,
  }));
}

/** For rankings table: exclude placeholders if desired, or include with flag */
function getRestaurantsForRankings(includePlaceholders = true) {
  const list = includePlaceholders ? RESTAURANTS : RESTAURANTS.filter((r) => r.slug && !r.slug.startsWith('placeholder'));
  return list.filter((r) => r.city && r.name);
}

/** Single restaurant by slug */
function getRestaurantBySlug(slug) {
  return RESTAURANTS.find((r) => r.slug === slug) || null;
}

/** Latest reviews (for home page cards) */
function getRecentRestaurants(limit = 4) {
  return RESTAURANTS.filter((r) => r.overallScore != null && !r.slug.startsWith('placeholder')).slice(0, limit);
}
